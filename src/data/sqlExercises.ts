// SQL exercise catalogue — Phase 6 M2 (plan §7). CLIENT-SAFE definitions.
//
// Every exercise here is safe to ship in the browser bundle: prompt, task,
// tables, constraint chips, optional setupSql (the setup IS the client-visible
// setup) and optional checkSql (reveals WHAT to inspect, never the expected
// values). Reference solutions, expected specs, hints and reveal content are
// compiled into the server only (src/server/sqlExercises.ts, sqlHints.ts,
// sqlReveals.ts) and reached through the gated reveal endpoint.
//
// Shared ids: `sql-<level>-<topic>-<nn>`. `qaId` tags the 13 exercises that
// carry a QA database-testing scenario (SQL-QA-01..13, plan §8). The registry
// is the single source of truth for the list; tests/data/sql-exercises.test.ts
// enforces the matrix (12 beginner + 13 intermediate + 11 advanced = 36).

export type SqlExerciseDifficulty = 'beginner' | 'intermediate' | 'advanced'
export type SqlExerciseKind = 'fundamentals' | 'qa'

export interface SqlExerciseDef {
  id: string
  title: string
  difficulty: SqlExerciseDifficulty
  estimatedMinutes: number
  /** One line for cards and hub grids. */
  summary: string
  /** One-paragraph QA-oriented framing — why a tester runs this query. */
  qaScenario: string
  objective: string
  /** The specific learner task (imperative). */
  task: string
  tables: string[]
  /** Constraint/index chips shown in the instructions panel. */
  relevantConstraints: string[]
  /** Client-visible setup applied after the canonical reseed (never for clean exercises by default). */
  setupSql?: string
  /** Post-state check for DML/transaction exercises — what to inspect, never expected values. */
  checkSql?: string
  /** SQL-QA-nn when this exercise carries a QA scenario (plan §8). */
  qaId?: string
  kind: SqlExerciseKind
  track: 'database-testing'
  /** What a good submission looks like (counts/columns, never values). */
  exampleEvidence: string
  relatedGuideIds: string[]
}

